export type PlatformErrorCode = (typeof PLATFORM_ERROR_CODES)[number];

export interface PublicError {
  readonly code: PlatformErrorCode;
  readonly category: PlatformErrorCategory;
  readonly status: number;
  readonly retryable: boolean;
  /** A deliberately generic message; clients must map code/category locally. */
  readonly message: string;
}

const KNOWN_PLATFORM_ERROR_CODES = new Set<string>(PLATFORM_ERROR_CODES);
const UNAUTHENTICATED_CODES = new Set<PlatformErrorCode>([
  'AUTH_INVALID_CREDENTIALS', 'AUTH_SESSION_INVALID', 'AUTH_SESSION_REFRESH_FAILED',
  'AUTH_RECOVERY_EXCHANGE_FAILED', 'BILLING_WEBHOOK_SIGNATURE_INVALID',
]);
const FORBIDDEN_CODES = new Set<PlatformErrorCode>([
  'FORBIDDEN', 'ENTITLEMENT_REQUIRED', 'AUTH_APP_NOT_ALLOWED',
  'AUTH_ORGANIZATION_ACCESS_DENIED', 'ACCOUNT_ACCESS_DENIED', 'FILE_ENTITLEMENT_REQUIRED',
  'JOB_ENTITLEMENT_REQUIRED', 'AI_GATEWAY_TRUST_DENIED', 'SEARCH_GATEWAY_TRUST_DENIED',
]);
const RESOURCE_EXHAUSTED_CODES = new Set<PlatformErrorCode>([
  'BUDGET_EXHAUSTED', 'AI_GATEWAY_COST_DENIED', 'SEARCH_GATEWAY_COST_DENIED',
]);

function publishedCode(error: unknown): PlatformErrorCode {
  if (
    typeof error === 'object' &&
    error !== null &&
    'code' in error &&
    typeof error.code === 'string' &&
    KNOWN_PLATFORM_ERROR_CODES.has(error.code)
  ) {
    return error.code as PlatformErrorCode;
  }
  return 'INTERNAL_ERROR';
}

function categoryFor(code: PlatformErrorCode): PlatformErrorCategory {
  if (code === 'INTERNAL_ERROR') return 'INTERNAL';
  if (code === 'RATE_LIMITED') return 'RATE_LIMITED';
  if (UNAUTHENTICATED_CODES.has(code)) return 'UNAUTHENTICATED';
  if (FORBIDDEN_CODES.has(code) || code.endsWith('_ACCESS_DENIED') || code.endsWith('_TRUST_DENIED')) return 'FORBIDDEN';
  if (RESOURCE_EXHAUSTED_CODES.has(code)) return 'RESOURCE_EXHAUSTED';
  if (code === 'APP_ALREADY_REGISTERED' || code.includes('_CONFLICT') || code.includes('_IDEMPOTENCY_') || code.includes('_INVALID_TRANSITION') || code.endsWith('_CONFIRMATION_REQUIRED')) return 'CONFLICT';
  if (code === 'NOT_FOUND' || code.endsWith('_NOT_FOUND') || code.endsWith('_NOT_REGISTERED') || code.endsWith('_NOT_AVAILABLE')) return 'NOT_FOUND';
  if (code === 'VALIDATION_FAILED' || code.startsWith('INVALID_') || code.includes('_INVALID_') || code.includes('_CONFIGURATION_INVALID') || code.includes('_SANITIZER_REQUIRED') || code.endsWith('_INVALID_POLICY')) return 'VALIDATION';
  if (code.includes('_UNAVAILABLE') || code.includes('_TIMEOUT') || code.includes('_FAILED') || code.endsWith('_NOT_CONFIGURED') || code === 'WORKER_LEASE_LOST' || code === 'JOB_FAILED') return 'UNAVAILABLE';
  return 'INTERNAL';
}

const STATUS_BY_CATEGORY: Readonly<Record<PlatformErrorCategory, number>> = Object.freeze({
  VALIDATION: 400,
  UNAUTHENTICATED: 401,
  FORBIDDEN: 403,
  NOT_FOUND: 404,
  CONFLICT: 409,
  RATE_LIMITED: 429,
  RESOURCE_EXHAUSTED: 409,
  UNAVAILABLE: 503,
  INTERNAL: 500,
});

/** Converts arbitrary failures into the only error payload allowed on HTTP. */
export function toPublicError(error: unknown): PublicError {
  const code = publishedCode(error);
  const category = categoryFor(code);
  return {
    code,
    category,
    status: STATUS_BY_CATEGORY[category],
    retryable: category === 'RATE_LIMITED' || category === 'UNAVAILABLE' || category === 'INTERNAL',
    message: 'Request could not be completed.',
  };
}
