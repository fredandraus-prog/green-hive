export const FILE_STATUSES = ['PROCESSING', 'READY', 'DELETED'] as const;
export type FileStatus = (typeof FILE_STATUSES)[number];

/**
 * Owner-visible file metadata. Storage authority and integrity fields are intentionally absent.
 */
export interface FileRecord {
  readonly id: string;
  readonly projectId: string;
  readonly originalFilename: string;
  readonly mediaType: string;
  readonly byteSize: number;
  readonly sensitivity: FileSensitivity;
  readonly status: 'READY';
  readonly createdAt: Date;
  readonly readyAt: Date;
}

/** Compatibility name for the safe owner-visible projection. */
export type StoredFile = FileRecord;

/** Short-lived authority returned only after the server has rechecked the owner scope. */
export interface FileDownloadGrant {
  readonly url: string;
  readonly expiresAt: Date;
}

export const FILE_SENSITIVITIES = [
  'PUBLIC',
  'INTERNAL',
  'CONFIDENTIAL',
  'HIGHLY_CONFIDENTIAL',
] as const;
export type FileSensitivity = (typeof FILE_SENSITIVITIES)[number];

/**
 * Server-side generated bytes. Callers cannot provide tenant, storage, status or integrity fields.
 */
export interface StoreGeneratedFileInput {
  readonly projectId: string;
  readonly idempotencyKey: string;
  readonly originalFilename: string;
  readonly mediaType: string;
  readonly content: Uint8Array;
}

export const FILE_ABSOLUTE_MAX_BYTES = 100 * 1024 * 1024;
